old_field_fn = 'function Field({\n  label,\n  placeholder,\n  type = \"text\",\n}: {\n  label: string;\n  placeholder?: string;\n  type?: string;\n}) {'
new_field_fn = 'function Field({\n  label,\n  placeholder,\n  type = \"text\",\n  name,\n}: {\n  label: string;\n  placeholder?: string;\n  type?: string;\n  name?: string;\n}) {'
